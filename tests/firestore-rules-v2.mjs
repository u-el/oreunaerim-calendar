import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, setDoc, getDoc, updateDoc, deleteDoc, collection, getDocs, serverTimestamp, Timestamp } from 'firebase/firestore';
import { readFileSync } from 'node:fs';
const env = await initializeTestEnvironment({projectId:'demo-moily',firestore:{rules:readFileSync('firestore.rules','utf8')}});
try {
 const a=env.authenticatedContext('alice').firestore(), b=env.authenticatedContext('bob').firestore(), guest=env.unauthenticatedContext().firestore();
 const path='accounts/alice/clubs/c1';
 const data={id:'c1',name:'Test',status:'active',schemaVersion:2,version:1,createdAt:serverTimestamp(),updatedAt:serverTimestamp(),deletedAt:null};
 await assertSucceeds(setDoc(doc(a,path),data));
 await assertSucceeds(getDoc(doc(a,path)));
 await assertFails(getDoc(doc(b,path)));
 await assertFails(getDoc(doc(guest,path)));
 await assertFails(updateDoc(doc(b,path),{name:'bad'}));
 await assertFails(deleteDoc(doc(a,path)));
 await assertFails(setDoc(doc(a,'accounts/alice/clubs/c2'),{...data,id:'c2',status:'invalid'}));
 await assertFails(updateDoc(doc(a,path),{name:'stale',version:1,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(doc(a,path),{status:'trashed',deletedAt:serverTimestamp(),version:2,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,path),{status:'active',deletedAt:null,version:3,updatedAt:serverTimestamp()}));
 const valid='a'.repeat(32), expired='b'.repeat(32), revoked='c'.repeat(32);
 await env.withSecurityRulesDisabled(async ctx=>{
  const db=ctx.firestore();
  await setDoc(doc(db,'sharesV2',valid),{snapshot:{title:'Test'},revokedAt:null,expiresAt:null});
  await setDoc(doc(db,'sharesV2',expired),{snapshot:{title:'Test'},revokedAt:null,expiresAt:Timestamp.fromMillis(1)});
  await setDoc(doc(db,'sharesV2',revoked),{snapshot:{title:'Test'},revokedAt:Timestamp.now(),expiresAt:null});
 });
 await assertSucceeds(getDoc(doc(guest,'sharesV2',valid)));
 await assertFails(getDoc(doc(guest,'sharesV2',expired)));
 await assertFails(getDoc(doc(guest,'sharesV2',revoked)));
 await assertFails(getDocs(collection(guest,'sharesV2')));
 await assertFails(setDoc(doc(a,'sharesV2','d'.repeat(32)),{revokedAt:null,expiresAt:null}));
 await assertSucceeds(setDoc(doc(a,'accounts/alice/schedules/legacy'),{id:'legacy',name:'Legacy',gear:[],certified:[]}));
 await assertFails(getDoc(doc(b,'accounts/alice/schedules/legacy')));
 const profile='accounts/alice/settings/moilyProfile';
 const draft={schemaVersion:2,nickname:'',interests:[],onboardingCompleted:false,createdAt:serverTimestamp(),updatedAt:serverTimestamp()};
 await assertSucceeds(getDoc(doc(a,profile)));
 await assertFails(setDoc(doc(b,profile),draft));
 await assertFails(setDoc(doc(guest,profile),draft));
 await assertSucceeds(setDoc(doc(a,profile),draft));
 await assertSucceeds(getDoc(doc(a,profile)));
 await assertFails(getDoc(doc(b,profile)));
 await assertFails(getDoc(doc(guest,profile)));
 await assertFails(updateDoc(doc(b,profile),{nickname:'bad',updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(doc(a,profile),{nickname:'테스트',interests:['hiking','running'],updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{nickname:'x'.repeat(21),updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{interests:['invalid'],updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{interests:Array(6).fill('hiking'),updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{onboardingCompleted:true,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{createdAt:Timestamp.fromMillis(1),updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{updatedAt:Timestamp.fromMillis(1)}));
 await assertFails(updateDoc(doc(a,profile),{extra:true,updatedAt:serverTimestamp()}));
 await assertFails(deleteDoc(doc(a,profile)));
 await assertFails(getDocs(collection(a,'accounts/alice/settings')));
 const consent='accounts/alice/settings/moilyConsent';
 const agreement={termsVersion:'test-1',privacyVersion:'test-1',termsAccepted:true,privacyAccepted:true,marketingAccepted:false,acceptedAt:serverTimestamp()};
 await assertSucceeds(getDoc(doc(a,consent)));
 await assertFails(setDoc(doc(b,consent),agreement));
 await assertFails(setDoc(doc(guest,consent),agreement));
 await assertFails(setDoc(doc(a,consent),{...agreement,termsAccepted:false}));
 await assertFails(setDoc(doc(a,consent),{...agreement,privacyAccepted:false}));
 await assertFails(setDoc(doc(a,consent),{...agreement,marketingAccepted:'yes'}));
 await assertFails(setDoc(doc(a,consent),{...agreement,termsVersion:'old'}));
 await assertFails(setDoc(doc(a,consent),{...agreement,privacyVersion:'old'}));
 await assertFails(setDoc(doc(a,consent),{...agreement,acceptedAt:Timestamp.fromMillis(1)}));
 await assertFails(setDoc(doc(a,consent),{...agreement,extra:true}));
 const {marketingAccepted,...missingMarketing}=agreement;
 await assertFails(setDoc(doc(a,consent),missingMarketing));
 await assertSucceeds(setDoc(doc(a,consent),agreement));
 await assertSucceeds(getDoc(doc(a,consent)));
 await assertSucceeds(setDoc(doc(b,'accounts/bob/settings/moilyConsent'),{...agreement,marketingAccepted:true}));
 await assertFails(getDoc(doc(b,consent)));
 await assertFails(getDoc(doc(guest,consent)));
 await assertFails(updateDoc(doc(a,consent),{marketingAccepted:true}));
 await assertFails(updateDoc(doc(b,consent),{marketingAccepted:true}));
 await assertFails(deleteDoc(doc(a,consent)));
 await assertFails(getDocs(collection(a,'accounts/alice/settings')));
 await assertFails(updateDoc(doc(a,profile),{nickname:'',onboardingCompleted:true,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(b,profile),{onboardingCompleted:true,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(guest,profile),{onboardingCompleted:true,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(doc(a,profile),{onboardingCompleted:true,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{onboardingCompleted:false,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(a,profile),{nickname:'',updatedAt:serverTimestamp()}));
 await assertFails(setDoc(doc(b,'accounts/bob/settings/moilyProfile'),{...draft,nickname:'Bob',onboardingCompleted:true}));
 await assertSucceeds(setDoc(doc(b,'accounts/bob/settings/moilyProfile'),{...draft,nickname:'Bob'}));
 await assertSucceeds(updateDoc(doc(b,'accounts/bob/settings/moilyProfile'),{onboardingCompleted:true,updatedAt:serverTimestamp()}));
 console.log('64 assertions passed');
} finally { await env.cleanup(); }
